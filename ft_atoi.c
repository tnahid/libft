#include "libft.h"

int	ft_atoi(const char *str)
{
	size_t	i;
	int		n;
	int		s;

	i = 0;
	n = 0;
	s = 1;
	while (str[i] == ' ' || (str[i] >= '\t'
			&& str[i] <= '\r'))
		i++;
	if (str[i] == '+' || str[i] == '-')
	{
		if (str[i] == '-')
			s = -s;
		i++;
	}
	while (str[i] >= '0' && str[i] <= '9')
	{
		n = n * 10 + str[i] - '0';
		i++;
	}
	return (n * s);
}
